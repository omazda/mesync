/* Плоский текст ответа — для поиска. */
function flatAnswer(blocks) {
  return blocks.map((b) => {
    if (typeof b === 'string') return b
    if (b.support) return `${b.support} поддержка написать`
    return b.list.join(' ')
  }).join(' ')
}

function AnswerBlocks({ blocks, onSupport }) {
  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: 8 }}>
      {blocks.map((b, i) => {
        if (typeof b === 'string') {
          return <div key={i} className="t-body-sm sec text-pretty">{b}</div>
        }
        if (b.support && HAS_SUPPORT) {
          return (
            <div key={i}>
              <div className="t-body-sm sec text-pretty">{b.support}</div>
              <div className="t-body-sm acc" onClick={onSupport}
                style={{ marginTop: 2, padding: '4px 0', fontWeight: 600, display: 'inline-flex', alignItems: 'center', gap: 5 }}>
                Написать в поддержку <Icon.arrowR size={15} />
              </div>
            </div>
          )
        }
        return (
          <div key={i} style={{ display: 'flex', flexDirection: 'column', gap: 6 }}>
            {b.list.map((li, j) => (
              <div key={j} className="t-body-sm sec" style={{ display: 'flex', gap: 8 }}>
                <span style={{ flex: '0 0 auto', color: 'var(--text-tertiary)' }}>{b.num ? `${j + 1}.` : '•'}</span>
                <span className="text-pretty" style={{ minWidth: 0 }}>{li}</span>
              </div>
            ))}
          </div>
        )
      })}
    </div>
  )
}

function FaqItem({ item, open, onToggle, onSupport }) {
  return (
    <>
      <div className="cell tap" style={{ minHeight: 0, padding: '12px 16px' }} onClick={onToggle}>
        <div className="cell-main" style={{ padding: 0 }}>
          <div className="t-headline text-pretty" style={{ fontSize: 15 }}>{item.q}</div>
        </div>
        <span className="chevron" style={{ transform: open ? 'rotate(90deg)' : 'none', transition: 'transform 0.2s ease' }}>
          <Icon.chevron size={17} />
        </span>
      </div>
      {open && <div style={{ padding: '0 16px 13px' }}><AnswerBlocks blocks={item.a} onSupport={onSupport} /></div>}
    </>
  )
}

/* ============================ S14 — Частые вопросы ============================ */
export function S14() {
  const [query, setQuery] = useState('')
  const [open, setOpen] = useState({})
  const supportRef = useRef(null)

  const q = query.trim().toLowerCase()
  const sections = useMemo(() => {
    if (!q) return FAQ
    return FAQ
      .map((s) => ({ ...s, items: s.items.filter((it) => `${it.q} ${flatAnswer(it.a)}`.toLowerCase().includes(q)) }))
      .filter((s) => s.items.length > 0)
  }, [q])

  const toggle = (key) => {
    host.haptic('selection')
    setOpen((v) => ({ ...v, [key]: !v[key] }))
  }

  // Ссылка «Написать в поддержку» из ответов ведёт к контактам внизу экрана.
  const scrollToSupport = () => {
    host.haptic('selection')
    supportRef.current?.scrollIntoView({ behavior: 'smooth', block: 'start' })
  }

  return (
    <Screen grouped>
      <HostHeader title="Частые вопросы" back onGrouped />
      <div className="screen-body grouped">
        <div className="body-pad" style={{ paddingTop: 8 }}>
          <div className="search">
            <Icon.search size={17} />
            <input placeholder="Поиск по вопросам" value={query} onChange={(e) => setQuery(e.target.value)} />
          </div>
        </div>
        {sections.map((s) => (
          <React.Fragment key={s.title}>
            <div className="cell-header caps">{s.title}</div>
            <div className="body-pad">
              <div className="island">
                {s.items.map((it) => (
                  // При активном поиске найденные вопросы раскрываем сразу.
                  <FaqItem key={it.q} item={it} open={q ? true : !!open[it.q]} onToggle={() => toggle(it.q)} onSupport={scrollToSupport} />
                ))}
              </div>
            </div>
          </React.Fragment>
        ))}
        {sections.length === 0 && (
          <div className="t-footnote sec text-pretty" style={{ textAlign: 'center', padding: '32px 28px' }}>
            Ничего не найдено.
          </div>
        )}
        {HAS_SUPPORT && (
          <div ref={supportRef}>
            <div className="cell-header caps">Поддержка</div>
            <div className="body-pad">
              <SupportIsland />
              <div className="t-footnote sec text-pretty" style={{ padding: '10px 2px 0' }}>
                Не нашли ответ — напишите нам, поможем разобраться.
              </div>
            </div>
          </div>
        )}
        <div style={{ height: 12 }} />
      </div>
      <TabFooter />
    </Screen>
  )
}
